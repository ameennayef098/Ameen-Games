def main():
    cats = json.load(open(CAT, encoding='utf-8'))
    have = {c['id'] for c in cats}
    names = {c['name'] for c in cats}
    added = []
    for spec in NEW:
        if spec['id'] in have:
            print('skip (id exists):', spec['id'])
            continue
        if spec['name'] in names:
            print('!! NAME CONFLICT:', spec['id'], spec['name'])
            continue
        gc, gi = G[spec['group']]
        cat = {
            'id': spec['id'], 'name': spec['name'], 'icon': spec['icon'],
            'description': spec['description'],
            'group': spec['group'], 'group_color': gc, 'group_icon': gi,
            'color': spec['color'],
        }
        cats.append(cat)
        have.add(cat['id'])
        names.add(cat['name'])
        added.append(cat)
    json.dump(cats, open(CAT, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    print('added %d categories -> total %d' % (len(added), len(cats)))
    for c in added:
        print('  +', c['id'], '|', c['name'], '|', c['icon'], '|', c['group'])


if __name__ == '__main__':
    main()
