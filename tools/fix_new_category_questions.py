def main():
    d = S.load_json(S.Q_FILE, [])
    used = set()
    fixed = 0
    out = []
    for q in d:
        t = str(q.get('question', '')).strip()
        hit = None
        for sub, nq, na in FIX:
            if sub in t and sub not in used:
                hit = (nq, na)
                used.add(sub)
                break
        if hit:
            nq, na = hit
            q['question'] = nq
            q['answer'] = na
            q['updated_at'] = S.now()
            fixed += 1
        out.append(q)
    S.save_json(S.Q_FILE, out)
    print('fixed %d / %d' % (fixed, len(FIX)))
    if fixed != len(FIX):
        print('NOT MATCHED:', [s for s, _, _ in FIX if s not in used])
    print('bank', len(out))


if __name__ == '__main__':
    main()
